#!/bin/sh
# generate-license-inventory.sh - derive THIRD_PARTY_LICENSES.md from the SPDX
# SBOMs written by generate-sbom.sh, and flag components whose license is
# unknown or outside the allowlist.
#
# Allowlist: security/license-allowlist.txt (one SPDX id per line) when present,
# otherwise the default below. Components with no license data fail the check;
# set CL_LICENSE_WARN_ONLY=1 to report without failing.
# Overrides: security/license-overrides.txt, lines "<purl-without-version> <SPDX
# expression>", for components built from source whose SBOM entry carries no
# license (for example pkg:generic/nginx BSD-2-Clause). Overridden licenses are
# marked "(reviewed)" in the inventory.
# Output: $CL_OUT/THIRD_PARTY_LICENSES.md (published with each release).
# shellcheck source=lib.sh
. "$(dirname -- "$0")/lib.sh"
cl_require jq

dir="$CL_OUT/sbom"
ls "$dir"/*.spdx-json.json >/dev/null 2>&1 || cl_die "no SPDX SBOMs in $dir; run 'make sbom' first"
allow="$CL_ROOT/security/license-allowlist.txt"
if [ -f "$allow" ]; then
	allowed=$(grep -v '^#' "$allow" | tr -s ' \n' ' ')
else
	allowed="Apache-2.0 BSD-2-Clause BSD-3-Clause GPL-2.0-only GPL-2.0-or-later LGPL-2.1-only LGPL-2.1-or-later MIT MPL-2.0 ISC Zlib OpenSSL PostgreSQL Unicode-3.0 Unicode-DFS-2016 curl X11 0BSD Public-Domain LicenseRef-Public-Domain"
fi
out="$CL_OUT/THIRD_PARTY_LICENSES.md"
rows="$CL_OUT/license-rows.txt"
: > "$rows"
for f in "$dir"/*.spdx-json.json; do
	jq -r '.packages[]? | select((.SPDXID | startswith("SPDXRef-DocumentRoot")) | not)
		| [.name, (.versionInfo // ""),
		   ((.licenseConcluded // "NOASSERTION") as $c | (.licenseDeclared // "NOASSERTION") as $d
		    | if $d != "NOASSERTION" and $d != "NONE" then $d elif $c != "NOASSERTION" and $c != "NONE" then $c else "UNKNOWN" end),
		   ((.externalRefs // []) | map(select(.referenceType == "purl") | .referenceLocator) | first // "")]
		| join("|")' "$f" >> "$rows"
done
sort -u "$rows" -o "$rows"
overrides="$CL_ROOT/security/license-overrides.txt"
if [ -f "$overrides" ]; then
	: > "$rows.new"
	while IFS='|' read -r name version lic purl; do
		if [ "$lic" = "UNKNOWN" ]; then
			key=${purl%%@*}
			o=$(awk -v k="$key" '$0 !~ /^#/ && $1 == k { $1 = ""; sub(/^ +/, ""); print; exit }' "$overrides")
			[ -z "$o" ] || lic="$o (reviewed)"
		fi
		printf '%s|%s|%s|%s\n' "$name" "$version" "$lic" "$purl" >> "$rows.new"
	done < "$rows"
	mv "$rows.new" "$rows"
fi
problems=0
{
	echo "# Third-party licenses"
	echo
	echo "Generated by scripts/generate-license-inventory.sh from the SPDX SBOMs of"
	echo "$(cl_project_name) (commit $(cl_git_ref)). This inventory lists the components"
	echo "found in the images and their declared licenses; it does not relicense anything."
	echo "License texts are in /usr/share/licenses/ inside each image."
	echo
	echo "| Component | Version | License | Package URL |"
	echo "|---|---|---|---|"
	while IFS='|' read -r name version lic purl; do
		echo "| $name | $version | $lic | \`$purl\` |"
	done < "$rows"
} > "$out"
while IFS='|' read -r name version lic purl; do
	if [ "$lic" = "UNKNOWN" ]; then
		cl_warn "license unknown: $name $version ($purl)"
		problems=$((problems + 1))
		continue
	fi
	for id in $(printf '%s\n' "$lic" | tr '()' '  '); do
		case "$id" in AND | OR | WITH | reviewed) continue ;; esac
		case " $allowed " in
		*" $id "*) ;;
		*)
			cl_warn "license outside the allowlist: $id ($name $version)"
			problems=$((problems + 1))
			;;
		esac
	done
done < "$rows"
cl_ok "$out ($(wc -l < "$rows") components)"
if [ "$problems" -gt 0 ]; then
	if [ -n "${CL_LICENSE_WARN_ONLY:-}" ]; then
		cl_warn "$problems license problem(s)"
	else
		cl_die "$problems license problem(s); extend security/license-allowlist.txt with a reviewed id or fix the component"
	fi
fi
